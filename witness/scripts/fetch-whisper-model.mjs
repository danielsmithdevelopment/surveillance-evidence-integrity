#!/usr/bin/env node
/**
 * Download a small English Whisper ggml model for on-device STT.
 * Intended for EAS / expo-dev-client builds (not Expo Go).
 *
 * Usage:
 *   node scripts/fetch-whisper-model.mjs           # tiny.en (~75MB)
 *   node scripts/fetch-whisper-model.mjs base.en   # larger, more accurate
 *
 * Writes:
 *   assets/models/ggml-<name>.bin
 *   src/whisper-model.generated.js  (Metro asset require)
 */
import { createWriteStream, existsSync, mkdirSync, writeFileSync, renameSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { pipeline } from "node:stream/promises";
import { Readable } from "node:stream";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const name = (process.argv[2] || "tiny.en").replace(/[^a-z0-9._-]/gi, "");
const file = `ggml-${name}.bin`;
const outDir = join(root, "assets", "models");
const outPath = join(outDir, file);
const partial = `${outPath}.partial`;

/** Hugging Face mirror of whisper.cpp ggml models */
const url = `https://huggingface.co/ggerganov/whisper.cpp/resolve/main/${file}`;

mkdirSync(outDir, { recursive: true });

if (existsSync(outPath) && !process.env.WHISPER_FORCE) {
  console.log(`Already present: ${outPath}`);
} else {
  console.log(`Fetching ${url}`);
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok || !res.body) {
    console.error(`Download failed: ${res.status} ${res.statusText}`);
    process.exit(1);
  }
  const total = Number(res.headers.get("content-length") || 0);
  let got = 0;
  let lastPct = -1;
  const body = Readable.fromWeb(res.body);
  body.on("data", (chunk) => {
    got += chunk.length;
    if (total > 0) {
      const pct = Math.floor((got / total) * 100);
      if (pct !== lastPct && pct % 5 === 0) {
        lastPct = pct;
        console.log(`  ${pct}% (${(got / 1e6).toFixed(1)} / ${(total / 1e6).toFixed(1)} MB)`);
      }
    }
  });
  await pipeline(body, createWriteStream(partial));
  renameSync(partial, outPath);
  console.log(`Wrote ${outPath} (${(got / 1e6).toFixed(1)} MB)`);
}

const genPath = join(root, "src", "whisper-model.generated.js");
writeFileSync(
  genPath,
  `/**
 * AUTO-GENERATED by scripts/fetch-whisper-model.mjs — do not edit.
 * Bundles ${file} into the native binary via Metro asset pipeline.
 */
module.exports = require("../assets/models/${file}");
`,
  "utf8"
);
console.log(`Updated ${genPath}`);
console.log(`\nNext:\n  export EXPO_PUBLIC_WHISPER=1\n  npx expo prebuild\n  eas build --profile preview --platform ios\n`);
